#!/usr/bin/env bun
/**
 * Rewrites lefthook's generated git hooks so they can find the local binary.
 *
 * `lefthook install` emits a hook that probes for its binary through an absolute
 * path it leaves **unquoted**. This repository lives under a path with a space
 * (`Github Projects/Sol Dex`), so the shell splits that path, every probe fails,
 * and each commit prints `Can't find lefthook in PATH` while still exiting 0 —
 * commitlint never runs.
 *
 * The hook is generated, so a patched copy would be lost on the next install.
 * This rewrites it from scratch instead, and `prepare` runs it immediately after
 * `bunx lefthook install`. Idempotent: identical content is never rewritten.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { isAbsolute, resolve } from 'node:path'

const HOOKS = ['commit-msg', 'prepare-commit-msg'] as const

function hookDir(): string {
  const path = execFileSync('git', ['rev-parse', '--git-path', 'hooks'], { encoding: 'utf8' }).trim()
  return isAbsolute(path) ? path : resolve(process.cwd(), path)
}

/**
 * Everything quoted, nothing relying on the caller's PATH or on `$dir` being the
 * workspace: the binary ships in `app/web/node_modules` while git roots itself
 * at the repository, one level up.
 */
const shim = (hook: string): string => `#!/bin/sh
#
# Generated by lefthook, repaired by app/web/scripts/fix-git-hooks.ts.
#
# lefthook's stock hook probes for its binary through an unquoted absolute path,
# which breaks in a checkout whose path contains a space. Resolve the workspace
# binary directly instead.
#
if [ "\${LEFTHOOK:-}" = "0" ]; then
  exit 0
fi

root="$(git rev-parse --show-toplevel)" || exit 0
cd "$root" || exit 0

bin=""
for candidate in "$root"/app/web/node_modules/lefthook-*/bin/lefthook "$root"/app/web/node_modules/.bin/lefthook; do
  if [ -x "$candidate" ]; then
    bin="$candidate"
    break
  fi
done

if [ -z "$bin" ]; then
  echo "git hook skipped: no lefthook binary — run 'bun install' in app/web"
  exit 0
fi

exec "$bin" run "${hook}" "$@"
`

const dir = hookDir()
let patched = 0

for (const name of HOOKS) {
  const file = resolve(dir, name)
  // A clone that never ran `bun install` has no hooks to repair.
  if (!existsSync(file)) continue

  const next = shim(name)
  if (readFileSync(file, 'utf8') === next) continue

  writeFileSync(file, next)
  patched += 1
  console.log(`rewrote .git/hooks/${name} to resolve lefthook directly`)
}

if (patched === 0) console.log('git hooks already resolve lefthook')
