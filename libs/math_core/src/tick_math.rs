//! Tick to sqrt-price conversion.
//!
//! A tick `t` corresponds to the price `1.0001^t`; the AMM stores
//! `sqrt(price)` in Q64.64 because every liquidity and swap formula is linear
//! in the square root of the price.
//!
//! `sqrt_price(t) = 1.0001^(t/2) * 2^64` is irrational for odd `t`, so it is
//! computed with the standard bit decomposition: `1.0001^(t/2)` is a product of
//! the precomputed [`TICK_RATIOS`], one per set bit of `t`, with a single
//! floor (or ceil) per factor. Each factor is a Q64.64 constant, so a factor
//! step costs one 128x128 multiply and a shift, and a whole conversion costs at
//! most 19 of them - no loop over the tick magnitude, and no `u128` division
//! except for the single reciprocal taken for negative ticks.
//!
//! Accuracy: the worst case measured against an 80-digit reference is
//! ~5 * 10^-19 relative, i.e. about 2^-61 - ten orders of magnitude finer than
//! the 5 * 10^-5 relative step between adjacent ticks. That is what makes
//! [`tick_at_sqrt_price`] an exact inverse of [`sqrt_price_at_tick`].

use crate::fixed_point::mul_shr;
use crate::u256::{self, U256};
use crate::{MathError, MathResult, Q64};

/// Highest usable tick: the price `1.0001^443636` is just below `2^64`, so its
/// square root fits in Q64.64 with the top bit to spare.
pub const MAX_TICK: i32 = 443_636;

/// Lowest usable tick, the mirror of [`MAX_TICK`].
pub const MIN_TICK: i32 = -MAX_TICK;

/// Largest sqrt price in Q64.64: `sqrt_price_at_tick(MAX_TICK)`.
pub const MAX_SQRT_PRICE: u128 = 79_226_673_515_401_279_963_822_778_343;

/// Smallest sqrt price in Q64.64: `sqrt_price_at_tick(MIN_TICK)`.
pub const MIN_SQRT_PRICE: u128 = 4_295_048_017;

/// `sqrt(1.0001)^(2^i)` in Q64.64, for `i` in `0..19`.
///
/// Generated by `tests/gen_vectors.py`; `MAX_TICK < 2^19`, so 19 factors cover
/// the whole range. The largest factor needs 83 bits.
pub const TICK_RATIOS: [u128; 19] = [
    18_447_666_387_855_959_850,
    18_448_588_748_116_922_571,
    18_450_433_606_991_734_263,
    18_454_123_878_217_468_680,
    18_461_506_635_090_006_701,
    18_476_281_010_653_910_144,
    18_505_865_242_158_250_041,
    18_565_175_891_880_433_522,
    18_684_368_066_214_940_582,
    18_925_053_041_275_764_671,
    19_415_764_168_677_886_926,
    20_435_687_552_633_177_494,
    22_639_080_592_224_303_007,
    27_784_196_929_998_399_742,
    41_848_122_137_994_986_128,
    94_936_283_578_220_370_716,
    488_590_176_327_622_479_860,
    12_941_056_668_319_229_769_860,
    9_078_618_265_828_848_800_676_189,
];

/// Whether `tick` is inside the usable range.
pub const fn is_valid_tick(tick: i32) -> bool {
    tick >= MIN_TICK && tick <= MAX_TICK
}

/// Whether `sqrt_price` is inside the usable range.
pub const fn is_valid_sqrt_price(sqrt_price: u128) -> bool {
    sqrt_price >= MIN_SQRT_PRICE && sqrt_price <= MAX_SQRT_PRICE
}

/// The Q64.64 square root of the price at `tick`.
///
/// Rounds down for non-negative ticks and up for negative ones, so the
/// returned price is never smaller than the true value for a tick at or below
/// zero and never larger above it. Either way the result is within a few
/// units in the last place of the exact value.
pub fn sqrt_price_at_tick(tick: i32) -> MathResult<u128> {
    if !is_valid_tick(tick) {
        return Err(MathError::TickOutOfBounds);
    }
    let ratio = tick_ratio_chain(tick.unsigned_abs())?;
    if tick >= 0 {
        Ok(ratio)
    } else {
        // S(-t) = 2^128 / S(t), truncated on the way in, so round the
        // reciprocal up: 2^64 * 2^64 / ratio.
        u256::div_shifted(U256::from_u128(Q64), 64, U256::from_u128(ratio), true)
    }
}

/// Product of [`TICK_RATIOS`] over the set bits of `magnitude`, rounded down.
fn tick_ratio_chain(magnitude: u32) -> MathResult<u128> {
    let mut ratio = Q64;
    for (i, factor) in TICK_RATIOS.iter().enumerate() {
        if magnitude & (1 << i) != 0 {
            ratio = mul_shr(ratio, *factor)?;
        }
    }
    Ok(ratio)
}

/// The largest tick whose [`sqrt_price_at_tick`] is at most `sqrt_price`.
///
/// Exact inverse of [`sqrt_price_at_tick`]: for every tick `t` in the usable
/// range, `tick_at_sqrt_price(sqrt_price_at_tick(t)) == t`.
pub fn tick_at_sqrt_price(sqrt_price: u128) -> MathResult<i32> {
    if !is_valid_sqrt_price(sqrt_price) {
        return Err(MathError::SqrtPriceOutOfBounds);
    }
    // Greedy bit search. Each step multiplies (or divides) by one precomputed
    // factor, so the search costs at most 38 factor steps regardless of the
    // size of the tick.
    let mut tick: i32 = 0;
    let mut ratio = Q64;
    for (i, factor) in TICK_RATIOS.iter().enumerate().rev() {
        let candidate = mul_shr(ratio, *factor)?;
        if candidate <= sqrt_price {
            ratio = candidate;
            tick += 1 << i;
        }
    }
    if ratio > sqrt_price {
        // Below 1.0: walk down into the negative ticks.
        let mut magnitude: u32 = 0;
        let mut chain = Q64;
        for (i, factor) in TICK_RATIOS.iter().enumerate().rev() {
            let candidate = mul_shr(chain, *factor)?;
            let price =
                u256::div_shifted(U256::from_u128(Q64), 64, U256::from_u128(candidate), true)?;
            if price >= sqrt_price {
                chain = candidate;
                magnitude += 1 << i;
            }
        }
        tick = -(magnitude as i32);
    }
    // The greedy search accumulates rounding in a different order than
    // `sqrt_price_at_tick`, so it can land one tick off. Settle it against the
    // authoritative function; in practice this runs zero or one iteration.
    if tick > MAX_TICK {
        tick = MAX_TICK;
    }
    if tick < MIN_TICK {
        tick = MIN_TICK;
    }
    while tick < MAX_TICK && sqrt_price_at_tick(tick + 1)? <= sqrt_price {
        tick += 1;
    }
    while tick > MIN_TICK && sqrt_price_at_tick(tick)? > sqrt_price {
        tick -= 1;
    }
    Ok(tick)
}

/// Alias for [`sqrt_price_at_tick`], kept for continuity with the original API.
pub fn tick_to_sqrt_price(tick: i32) -> MathResult<u128> {
    sqrt_price_at_tick(tick)
}

/// Alias for [`tick_at_sqrt_price`], kept for continuity with the original API.
pub fn sqrt_price_to_tick(sqrt_price: u128) -> MathResult<i32> {
    tick_at_sqrt_price(sqrt_price)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::fixed_point::div_shr;
    use crate::Q64;

    #[test]
    fn bounds_are_rejected() {
        assert_eq!(
            sqrt_price_at_tick(MAX_TICK + 1),
            Err(MathError::TickOutOfBounds)
        );
        assert_eq!(
            sqrt_price_at_tick(MIN_TICK - 1),
            Err(MathError::TickOutOfBounds)
        );
        assert_eq!(
            sqrt_price_at_tick(i32::MAX),
            Err(MathError::TickOutOfBounds)
        );
        assert_eq!(
            tick_at_sqrt_price(MAX_SQRT_PRICE + 1),
            Err(MathError::SqrtPriceOutOfBounds)
        );
        assert_eq!(
            tick_at_sqrt_price(MIN_SQRT_PRICE - 1),
            Err(MathError::SqrtPriceOutOfBounds)
        );
        assert_eq!(tick_at_sqrt_price(0), Err(MathError::SqrtPriceOutOfBounds));
    }

    #[test]
    fn endpoints_match_the_declared_constants() {
        assert_eq!(sqrt_price_at_tick(MAX_TICK).unwrap(), MAX_SQRT_PRICE);
        assert_eq!(sqrt_price_at_tick(MIN_TICK).unwrap(), MIN_SQRT_PRICE);
        assert_eq!(tick_at_sqrt_price(MAX_SQRT_PRICE).unwrap(), MAX_TICK);
        assert_eq!(tick_at_sqrt_price(MIN_SQRT_PRICE).unwrap(), MIN_TICK);
        // The price format bound: sqrt price at MAX_TICK stays below 2^96,
        // which keeps `price <= 2^64`.
        assert!(MAX_SQRT_PRICE < 1u128 << 96);
    }

    #[test]
    fn tick_zero_is_one() {
        assert_eq!(sqrt_price_at_tick(0).unwrap(), Q64);
        assert_eq!(tick_at_sqrt_price(Q64).unwrap(), 0);
    }

    #[test]
    fn price_at_tick_is_strictly_increasing() {
        let mut previous = 0u128;
        for tick in (MIN_TICK..=MAX_TICK).step_by(997) {
            let price = sqrt_price_at_tick(tick).unwrap();
            assert!(price > previous, "not increasing at tick {tick}");
            previous = price;
        }
    }

    #[test]
    fn round_trip_is_exact_on_samples() {
        for tick in (MIN_TICK..=MAX_TICK).step_by(997) {
            let price = sqrt_price_at_tick(tick).unwrap();
            assert_eq!(tick_at_sqrt_price(price).unwrap(), tick, "tick {tick}");
        }
        for tick in [
            0, 1, -1, 60, -60, 100, -100, 123_456, -123_456, 8_877, -8_877,
        ] {
            let price = sqrt_price_at_tick(tick).unwrap();
            assert_eq!(tick_at_sqrt_price(price).unwrap(), tick, "tick {tick}");
        }
    }

    #[test]
    fn round_trip_is_exact_on_every_tick() {
        for tick in MIN_TICK..=MAX_TICK {
            let price = sqrt_price_at_tick(tick).unwrap();
            let back = tick_at_sqrt_price(price).unwrap();
            assert_eq!(back, tick, "tick {tick}");
        }
    }

    #[test]
    fn prices_between_ticks_resolve_to_the_lower_tick() {
        for tick in [-50_000, -1, 0, 1, 50_000, 443_000] {
            let low = sqrt_price_at_tick(tick).unwrap();
            let high = sqrt_price_at_tick(tick + 1).unwrap();
            // A price strictly inside the tick's range belongs to the lower tick.
            if high > low + 2 {
                let mid = low + (high - low) / 2;
                assert_eq!(tick_at_sqrt_price(mid).unwrap(), tick, "tick {tick}");
                assert_eq!(tick_at_sqrt_price(high - 1).unwrap(), tick, "tick {tick}");
            }
        }
    }

    #[test]
    fn aliases_agree_with_canonical_names() {
        assert_eq!(
            tick_to_sqrt_price(60).unwrap(),
            sqrt_price_at_tick(60).unwrap()
        );
        assert_eq!(
            sqrt_price_to_tick(Q64 + 1).unwrap(),
            tick_at_sqrt_price(Q64 + 1).unwrap()
        );
    }

    #[test]
    fn tick_ranges_are_usable() {
        assert!(is_valid_tick(MAX_TICK) && is_valid_tick(MIN_TICK));
        assert!(!is_valid_tick(MAX_TICK + 1) && !is_valid_tick(MIN_TICK - 1));
        assert!(is_valid_sqrt_price(MAX_SQRT_PRICE) && is_valid_sqrt_price(MIN_SQRT_PRICE));
    }

    #[test]
    fn ratio_chain_matches_direct_multiplication() {
        // The chain is the product of the ratios over the set bits.
        let magnitude = 0b1011u32;
        let expected = mul_shr(
            mul_shr(mul_shr(Q64, TICK_RATIOS[0]).unwrap(), TICK_RATIOS[1]).unwrap(),
            TICK_RATIOS[3],
        )
        .unwrap();
        assert_eq!(tick_ratio_chain(magnitude).unwrap(), expected);
        assert_eq!(tick_ratio_chain(0).unwrap(), Q64);
    }

    #[test]
    fn negative_ticks_round_their_reciprocal_up() {
        // S(-1) = ceil(2^128 / S(1)); with div_shifted that is a ceil division.
        let positive = sqrt_price_at_tick(1).unwrap();
        let expected =
            u256::div_shifted(U256::from_u128(Q64), 64, U256::from_u128(positive), true).unwrap();
        assert_eq!(sqrt_price_at_tick(-1).unwrap(), expected);
        // The truncating version of the same reciprocal is one below at most.
        let floor = div_shr(Q64, positive).unwrap();
        assert!(floor <= expected && expected - floor <= 1);
    }
}
